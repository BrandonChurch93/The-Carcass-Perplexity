export const SENSOR_HEIGHT_MM = 24;
export const STEP = 6;
export const BLACK = 'black';

export const lensMm = (fovDegrees) => SENSOR_HEIGHT_MM / 2 / Math.tan((fovDegrees * Math.PI) / 360);

const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);

export function sampleFrames(shot, keyFrame = null, step = STEP) {
  const out = new Set();
  for (let f = shot.first; f <= shot.last; f += step) out.add(f);
  out.add(shot.last);
  if (keyFrame !== null && keyFrame >= shot.first && keyFrame <= shot.last) out.add(keyFrame);
  return [...out].sort((a, b) => a - b);
}

export function measure(shot, states, keyFrame = null) {
  if (!states.length) throw new Error(`The shot ${shot.id} has no states`);
  const first = states[0];
  const last = states[states.length - 1];
  const key = keyFrame === null ? null : (states.find((s) => s.frame === keyFrame) ?? null);
  let travel = 0;
  for (let i = 1; i < states.length; i++) travel += dist(states[i].camera.position, states[i - 1].camera.position);
  const lens = (s) => lensMm(s.camera.lens.fovDegrees);
  const reach = (s) => dist(s.camera.position, s.camera.aim);
  const lenses = states.map(lens);
  return {
    frames: shot.last - shot.first + 1,
    lensStart: lens(first),
    lensEnd: lens(last),
    lensKey: key ? lens(key) : null,
    lensMin: Math.min(...lenses),
    lensMax: Math.max(...lenses),
    fovStart: first.camera.lens.fovDegrees,
    fovEnd: last.camera.lens.fovDegrees,
    travel,
    heightStart: first.camera.height,
    heightEnd: last.camera.height,
    heightKey: key ? key.camera.height : null,
    reachStart: reach(first),
    reachEnd: reach(last),
    aperture: Math.max(...states.map((s) => s.camera.lens.aperture ?? 0)),
  };
}

export function length(value, scale = 'm') {
  if (!Number.isFinite(value)) return 'unknown';
  if (scale === 'km') return value >= 100 ? `${Math.round(value)} km` : value >= 10 ? `${value.toFixed(1)} km` : `${value.toFixed(2)} km`;
  if (value >= 10000) return `${(value / 1000).toFixed(1)} km`;
  if (value >= 100) return `${Math.round(value / 10) * 10} m`;
  if (value >= 10) return `${Math.round(value)} m`;
  return `${value.toFixed(1)} m`;
}

export function lensLine(m) {
  const mm = (v) => `${Math.round(v)} mm`;
  const held = Math.abs(m.lensMax - m.lensMin) < 0.5;
  if (held) return `${mm(m.lensStart)} for the whole shot (a vertical field of view of ${Math.round(m.fovStart)} degrees)`;
  return `from ${mm(m.lensStart)} to ${mm(m.lensEnd)} (a vertical field of view from ${Math.round(m.fovStart)} to ${Math.round(m.fovEnd)} degrees)`;
}

export const MOVES = { in: 'in', out: 'out', left: 'to the left', right: 'to the right', hold: 'a hold that drifts' };

export function shotBlock(shot, m, note, { fps, keyFrame, scale = 'm' }) {
  const seconds = ((shot.last - shot.first + 1) / fps).toFixed(2);
  const lines = [`### \`${shot.id}\` · ${shot.label}`, ''];
  lines.push(`- Frames: ${shot.first} to ${shot.last}, ${seconds} s.`);
  if (shot.picture === BLACK) {
    lines.push('- Picture: black. No camera.');
    return lines.join('\n');
  }
  lines.push(`- Key: ${shot.key ? `\`${shot.key}\` at frame ${keyFrame}` : `none of its own. It is cut from the picture \`${shot.picture}\``}.`);
  lines.push(`- Lens: ${lensLine(m)}.`);
  const climb = Math.abs(m.heightEnd - m.heightStart) < 0.02 * Math.max(m.heightStart, m.heightEnd, 1e-9) ? `at ${length(m.heightStart, scale)} above the ground` : `from ${length(m.heightStart, scale)} above the ground to ${length(m.heightEnd, scale)}`;
  lines.push(`- Move: ${MOVES[shot.move] ?? shot.move}. The camera travels ${length(m.travel, scale)}, ${climb}.${note?.move ? ` ${note.move}` : ''}`);
  lines.push(`- Start framing: ${note?.start ?? 'not written'}`);
  lines.push(`- End framing: ${note?.end ?? 'not written'}`);
  const depth = m.aperture > 0 ? `Focus is pulled from ${length(m.reachStart, scale)} to ${length(m.reachEnd, scale)}.` : `The aim is ${length(m.reachStart, scale)} away at the start and ${length(m.reachEnd, scale)} at the end. Depth of field is off in the blockout.`;
  lines.push(`- Focus: ${note?.focus ?? 'not written'} ${depth}`);
  return lines.join('\n');
}

export function shotsDoc({ cut, cfg, measures, notes, title = 'Shots' }) {
  const missing = [];
  const out = [`# ${title}`, '', 'Written by `npm run shots` from the cut list, the cameras of the built page and `cut/SHOTS.notes.json`. The lens is given as the focal length on a sensor 24 mm high. Do not edit this file: change the cameras or the notes and run the command again.', ''];
  for (const unit of cfg.film.order) {
    const place = cut.places.find((p) => p.unit === unit);
    const shots = cut.shots.filter((s) => s.unit === unit);
    const name = cfg.units.find((u) => u.id === unit)?.name ?? unit;
    out.push(`## ${name}`, '', `Frames ${place.first} to ${place.last}, ${((place.last - place.first + 1) / cut.fps).toFixed(2)} s, ${shots.length} ${shots.length === 1 ? 'shot' : 'shots'}.${notes?.places?.[unit] ? ` ${notes.places[unit]}` : ''}`, '');
    for (const shot of shots) {
      const note = notes?.shots?.[shot.id] ?? null;
      if (shot.picture !== BLACK) for (const k of ['start', 'end', 'focus']) if (!note?.[k]) missing.push(`${shot.id}: ${k}`);
      out.push(shotBlock(shot, measures[shot.id] ?? null, note, { fps: cut.fps, keyFrame: shot.key ? cut.keyFrames[shot.key] : null, scale: notes?.scale?.[unit] ?? 'm' }), '');
    }
  }
  return { text: `${out.join('\n').trimEnd()}\n`, missing };
}
